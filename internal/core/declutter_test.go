func TestDuplicateScanMatchesRustGroupIdentityAndKeepsOldestCopy(t *testing.T) {
	s, err := CurrentRules()
	if err != nil {
		t.Fatal(err)
	}
	root := t.TempDir()
	data := make([]byte, 65536)
	for i := range data {
		data[i] = byte((i*73 + 19) % 251)
	}
	old := time.Unix(1600000000, 0)
	writeDeclutterFile(t, root, "new.pdf", data, old.Add(24*time.Hour))
	writeDeclutterFile(t, root, "old.pdf", data, old)
	different := bytes.Clone(data)
	different[10000] ^= 0xff
	writeDeclutterFile(t, root, "not-duplicate.pdf", different, old.Add(-24*time.Hour))
	writeDeclutterFile(t, root, "small-a.txt", data[:65535], old)
	writeDeclutterFile(t, root, "small-b.txt", data[:65535], old)
	groups := ScanDuplicateFiles(context.Background(), s, []string{root}, nil)
	if len(groups) != 1 {
		t.Fatalf("duplicate groups: %+v", groups)
	}
	g := groups[0]
	// Generated by the unchanged Rust compute_hashes and DefaultHasher.
	if g.ID != "dup-65536-3244738833857451109" || g.Filename != "old.pdf" || g.Category.Get(English) != "Documents" || len(g.Files) != 2 || g.CleanableSize() != 65536 {
		t.Fatalf("group: %+v", g)
	}
	if !g.Files[0].IsOriginal || g.Files[0].Selected || g.Files[1].IsOriginal || !g.Files[1].Selected || g.Files[0].ModifiedAtStr != "2020-09-13" {
		t.Fatalf("copy selection: %+v", g.Files)
	}
	groups[0].Files[1].Selected = false
	if groups[0].CleanableSize() != 0 {
		t.Fatal("selection did not update reclaimable bytes")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if got := ScanDuplicateFiles(ctx, s, []string{root}, nil); len(got) != 0 {
		t.Fatal("cancelled duplicate scan returned work")
	}
}

func TestSimilarPhotosDecodedGroupingAndBestShot(t *testing.T) {
	snapshot, err := CurrentRules()
	if err != nil {
		t.Fatal(err)
	}
	s := &RuleSnapshot{Bundle: clonePlanValue(snapshot.Bundle)}
	s.Definition("engine").Numbers["photo_min_size"] = 1
	home, err := os.UserHomeDir()
	if err != nil {
		t.Fatal(err)
	}
	// Photo discovery excludes every ignored path component, including /tmp.
	root, err := os.MkdirTemp(home, "quickcleaner-photos-test-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(root) })
	encode := func(w, h int, reverse bool) []byte {
		img := image.NewGray(image.Rect(0, 0, w, h))
		for y := range h {
			for x := range w {
				value := uint8(20)
				if (x*9/w >= 4) != reverse {
					value = 200
				}
				img.SetGray(x, y, color.Gray{Y: value})
			}
		}
		var buf bytes.Buffer
		if err := png.Encode(&buf, img); err != nil {
			t.Fatal(err)
		}
		return buf.Bytes()
	}
	old := time.Unix(1600000000, 0)
	low := append(encode(9, 8, false), make([]byte, 12000)...)
	writeDeclutterFile(t, root, "a-original.png", low, old)
	writeDeclutterFile(t, root, "b-high-resolution.png", encode(18, 16, false), old.Add(time.Hour))
	writeDeclutterFile(t, root, "c-unrelated.png", encode(9, 8, true), old)
	writeDeclutterFile(t, root, "d-different-aspect.png", encode(9, 16, false), old)
	writeDeclutterFile(t, root, "site/ignored.png", low, old)
	writeDeclutterFile(t, root, "other.txt", low, old)
	groups := ScanSimilarPhotos(context.Background(), s, []string{root}, nil)
	if len(groups) != 1 || len(groups[0].Photos) != 2 || groups[0].IndexStr != "01" || groups[0].Title.Get(English) != "Series: a-original" {
		t.Fatalf("photo groups: %+v", groups)
	}
	g := groups[0]
	if g.Photos[0].ID != "photo-0-0" || g.Photos[0].IsBestShot || !g.Photos[0].Selected || !g.Photos[1].IsBestShot || g.Photos[1].Selected || g.Photos[1].Dimensions != [2]uint32{18, 16} || g.Photos[0].DateStr != "2020-09-13" || g.SelectedCount() != 1 || g.CleanableSize() != uint64(len(low)) {
		t.Fatalf("best shot must prioritize resolution over bytes: %+v", g)
	}
	s.Definition("engine").Numbers["photo_group_size_limit"] = 1
	if got := ScanSimilarPhotos(context.Background(), s, []string{root}, nil); len(got) != 0 {
		t.Fatal("group size limit ignored")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if got := ScanSimilarPhotos(ctx, s, []string{root}, nil); len(got) != 0 {
		t.Fatal("cancelled photo scan returned work")
	}
}

func TestDuplicateScanTwoMiBBoundaryMatchesRust(t *testing.T) {
	s, err := CurrentRules()
	if err != nil {
		t.Fatal(err)
	}
	for size, hash := range map[int]string{2097152: "12463943658468099991", 2097153: "4661102407099271872"} {
		t.Run(strconv.Itoa(size), func(t *testing.T) {
			root := t.TempDir()
			data := make([]byte, size)
			for i := range data {
				data[i] = byte((i*73 + 19) % 251)
			}
			old := time.Unix(1600000000, 0)
			writeDeclutterFile(t, root, "a.bin", data, old)
			writeDeclutterFile(t, root, "b.bin", data, old.Add(time.Hour))
			data[size/2] ^= 0xff
			writeDeclutterFile(t, root, "different.bin", data, old.Add(-time.Hour))
			groups := ScanDuplicateFiles(context.Background(), s, []string{root}, nil)
			if len(groups) != 1 || groups[0].ID != "dup-"+strconv.Itoa(size)+"-"+hash || len(groups[0].Files) != 2 || groups[0].Files[0].Path != filepath.Join(root, "a.bin") {
				t.Fatalf("Rust hash/selection parity at 2 MiB boundary: %+v", groups)
			}
		})
	}
}


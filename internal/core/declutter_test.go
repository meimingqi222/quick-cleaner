func writeDeclutterFile(t *testing.T, root, relative string, data []byte, mtime time.Time) string {
	t.Helper()
	path := filepath.Join(root, relative)
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, data, 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.Chtimes(path, mtime, mtime); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestDeclutterDownloadsAndLargeFilePolicies(t *testing.T) {
	snapshot, err := CurrentRules()
	if err != nil {
		t.Fatal(err)
	}
	s := &RuleSnapshot{Bundle: clonePlanValue(snapshot.Bundle)}
	root := t.TempDir()
	now := time.Now()
	writeDeclutterFile(t, root, "installer.EXE", bytes.Repeat([]byte("a"), 200), now.Add(-90*24*time.Hour))
	writeDeclutterFile(t, root, "nested/a/b/report.PDF", bytes.Repeat([]byte("b"), 199), now.Add(-89*24*time.Hour))
	writeDeclutterFile(t, root, "future.zip", bytes.Repeat([]byte("c"), 128), now.Add(24*time.Hour))
	writeDeclutterFile(t, root, "below.bin", bytes.Repeat([]byte("d"), 127), now.Add(-31*24*time.Hour))
	writeDeclutterFile(t, root, "nested/a/b/c/too-deep.pdf", []byte("not in downloads"), now)
	items := ScanDownloads(context.Background(), s, root, nil)
	if len(items) != 4 || items[0].Filename != "future.zip" || items[0].Kind.Get(English) != "Archive" || items[0].DownloadedAtStr.Get(English) != "Just now" {
		t.Fatalf("downloads: %+v", items)
	}
	for _, item := range items {
		if item.Selected {
			t.Fatal("downloads must require explicit selection")
		}
		if item.Filename == "installer.EXE" && item.Kind.Get(Chinese) != "安装包" {
			t.Fatal("installer classification/localization changed")
		}
	}
	s.Definition("engine").Numbers["large_result_limit"] = 2
	large := ScanLargeOldFiles(context.Background(), s, []string{root}, 128, nil)
	if len(large) != 2 || large[0].Filename != "installer.EXE" || large[0].Size != 200 || !large[0].Selected || large[0].LastAccessedStr.Get(English) != "3 months ago" || large[0].IconType != 3 || large[1].Filename != "report.PDF" || large[1].Selected || large[1].Kind.Get(English) != "Documents" || large[1].IconType != 2 {
		t.Fatalf("large files: %+v", large)
	}
	s.Definition("engine").Numbers["large_result_limit"] = 0
	if got := ScanLargeOldFiles(context.Background(), s, []string{root}, 128, nil); len(got) != 0 {
		t.Fatal("result limit ignored")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if len(ScanDownloads(ctx, s, root, nil)) != 0 || len(ScanLargeOldFiles(ctx, s, []string{root}, 1, nil)) != 0 || len(ScanDownloads(context.Background(), s, "", nil)) != 0 {
		t.Fatal("cancellation/unavailable download root ignored")
	}
}

